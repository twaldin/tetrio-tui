/** Logical size name -> font table key. */
const SIZE_FONT: Record<string, string> = {
  small: 'SMALL', medium: 'STANDARD', big: 'BIG', banner: 'BANNER3', mini: 'MINI', block: 'BLOCK',
};
export type BigTextSize = 'small' | 'medium' | 'big' | 'banner' | 'mini' | 'block';

const GAP = 1;

function glyphsFor(size: string): Record<string, string[]> {
  const key = SIZE_FONT[size] ?? 'BIG';
  return key === 'BLOCK' ? BLOCK : FONTS[key];
}

function glyphWidth(g: string[]): number {
  let w = 0;
  for (const r of g) w = Math.max(w, r.length);
  return w;
}

/** Measure a big-text string. `diagonal` adds width for the staircase slant. */
export function measureBigText(text: string, size: BigTextSize = 'big', diagonal = false): { width: number; height: number } {
  const glyphs = glyphsFor(size);
  const h = FONT_HEIGHT[SIZE_FONT[size] ?? 'BIG'];
  let width = 0;
  for (let i = 0; i < text.length; i++) {
    const g = glyphs[text[i].toUpperCase()];
    if (!g) { width += 2; continue; }
    if (i > 0) width += GAP;
    width += glyphWidth(g);
  }
  if (diagonal) width += h - 1;
  return { width, height: h };
}

/** Render big text at (x, y). If `diagonal`, each row shifts right (staircase slant). */
export function renderBigText(
  buf: RenderBuffer, x: number, y: number, text: string, style: Style,
  size: BigTextSize = 'big', diagonal = false,
): number {
  const glyphs = glyphsFor(size);
  let cx = x;
  for (let i = 0; i < text.length; i++) {
    const g = glyphs[text[i].toUpperCase()];
    if (!g) { cx += 2; continue; }
    if (i > 0) cx += GAP;
    for (let row = 0; row < g.length; row++) {
      const line = g[row];
      const xoff = diagonal ? row : 0;
      for (let col = 0; col < line.length; col++) {
        if (line[col] !== ' ') buf.set(cx + col + xoff, y + row, line[col], style);
      }
    }
    cx += glyphWidth(g);
  }
  return cx - x;
}

/** Render big text centered horizontally at cx. */
export function renderBigTextCentered(
  buf: RenderBuffer, cx: number, y: number, text: string, style: Style,
  size: BigTextSize = 'big', diagonal = false,
): number {
  const { width } = measureBigText(text, size, diagonal);
  const startX = cx - Math.floor(width / 2);
  renderBigText(buf, startX, y, text, style, size, diagonal);
  return startX;
}

/** Combo number size — GROWS with the combo (small -> medium -> big). */
export function comboSize(combo: number): BigTextSize {
  return combo >= 5 ? 'big' : combo >= 3 ? 'medium' : 'small';
}

/** Render a combo counter as a simple "COMBO x3" text line (legacy helper). */
export function renderComboCounter(
  buf: RenderBuffer, x: number, y: number, combo: number, color: RGB, _accentColor: RGB,
): { width: number; height: number } {
  const label = `COMBO x${combo}`;
  buf.drawText(x, y, label, { fg: color, bold: true });
  return { width: label.length, height: 1 };
}

/** Render a B2B counter as a simple "B2B x2" text line (legacy helper). */
export function renderB2BCounter(
  buf: RenderBuffer, x: number, y: number, b2b: number, color: RGB,
): { width: number; height: number } {
  const label = `B2B x${b2b}`;
  buf.drawText(x, y, label, { fg: color, bold: true });
  return { width: label.length, height: 1 };
}

/** Render a clear-type label (SINGLE, QUAD, ...) in a Figlet font. */
export function renderClearLabel(
  buf: RenderBuffer, x: number, y: number, clearType: string, color: RGB,
  size: BigTextSize = 'small', diagonal = false,
): number {
  return renderBigText(buf, x, y, clearType, { fg: color, bold: true }, size, diagonal);
}
